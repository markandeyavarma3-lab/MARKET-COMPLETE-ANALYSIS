    ')\n'
    'nifty = float(nr[0]["close"]) if nr else 0.0\n'
    '# Try HMM regime first, fall back to price-based\n'
    'hmm_rows = qdb(\n'
    '    "SELECT regime, bull_prob, bear_prob, sideways_prob"\n'
    '    " FROM hmm_regime_daily ORDER BY date DESC LIMIT 1"\n'
    ')\n'
    'if hmm_rows:\n'
    '    regime     = hmm_rows[0]["regime"]\n'
    '    bull_p     = hmm_rows[0]["bull_prob"]\n'
    '    bear_p     = hmm_rows[0]["bear_prob"]\n'
    'else:\n'
    '    regime = "BULLISH" if nifty > 22000 else "SIDEWAYS" if nifty > 18000 else "BEARISH" if nifty > 0 else "UNKNOWN"\n'
    '    bull_p = bear_p = None'
