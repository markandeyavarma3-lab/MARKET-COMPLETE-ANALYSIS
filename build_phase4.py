    '        " WHERE symbol=\'NIFTY\' ORDER BY date DESC LIMIT 1"',
    '      ).get() as { atm_iv: number; iv_rank: number } | undefined;',
    '    } catch { return undefined; }',
    '  }, undefined);',
    '  result.atm_iv  = ivRow?.atm_iv;',
    '  result.iv_rank = ivRow?.iv_rank;',
    '',
    '  // Participant OI',
    '  const partOI = safeDb(db => {',
